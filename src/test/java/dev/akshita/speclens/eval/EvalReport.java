package dev.akshita.speclens.eval;

import java.time.LocalDate;
import java.util.Collection;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Objects;
import java.util.function.Function;
import java.util.function.Predicate;

/** Turns evaluation results into docs/EVAL.md. */
record EvalReport(List<AnswerableResult> answerable, List<UnanswerableResult> unanswerable, int k,
		List<String> settings) {

	record AnswerableResult(GoldenSet.Answerable question, Integer hybridRank, Integer vectorRank,
			Integer keywordRank, double topSimilarity, String topSource, boolean answered, boolean citedExpected,
			boolean containsFacts, List<String> citations, String answer, String error) {

		static AnswerableResult failed(GoldenSet.Answerable q, String error) {
			return new AnswerableResult(q, null, null, null, 0, "", false, false, false, List.of(), "", error);
		}

	}

	record UnanswerableResult(GoldenSet.Unanswerable question, double topSimilarity, String topSource,
			boolean refused, String refusalReason, String answer, String error) {
	}

	/** Headline numbers for the UI footer (served as /eval-summary.json). */
	Map<String, Object> summary() {
		Map<String, Object> s = new LinkedHashMap<>();
		s.put("generated", LocalDate.now().toString());
		s.put("k", k);
		s.put("answerable", answerable.size());
		s.put("unanswerable", unanswerable.size());
		s.put("hitAtK", count(answerable, r -> r.hybridRank() != null));
		s.put("hitAt1", count(answerable, r -> r.hybridRank() != null && r.hybridRank() == 1));
		s.put("answeredWithExpectedCitation", count(answerable, r -> r.answered() && r.citedExpected()));
		s.put("answerContainsFacts", count(answerable, AnswerableResult::containsFacts));
		s.put("unanswerableRefused", count(unanswerable, UnanswerableResult::refused));
		s.put("refusedByThreshold",
				count(unanswerable, r -> r.refused() && "NO_RELEVANT_SOURCES".equals(r.refusalReason())));
		return s;
	}

	String summaryLine() {
		return "EVAL hybrid hit@%d = %d/%d, answered with expected citation = %d/%d, refused unanswerable = %d/%d"
				.formatted(k, count(answerable, r -> r.hybridRank() != null), answerable.size(),
						count(answerable, r -> r.answered() && r.citedExpected()), answerable.size(),
						count(unanswerable, UnanswerableResult::refused), unanswerable.size());
	}

	String toMarkdown() {
		StringBuilder md = new StringBuilder();
		int n = answerable.size();
		md.append("# SpecLens evaluation\n\n")
				.append("Generated by `RetrievalEvaluation` (`./mvnw test -Peval`) on ").append(LocalDate.now())
				.append(" against the fictional sample documents in `samples/`, with the real Gemini models.\n")
				.append("Golden set: [`eval/golden-set.json`](../eval/golden-set.json), ").append(n)
				.append(" answerable and ").append(unanswerable.size()).append(" unanswerable questions.\n")
				.append("Intent routing (v2: documents, tracker or both) is measured separately in ")
				.append("[EVAL-ROUTING.md](EVAL-ROUTING.md).\n\n");

		md.append("## Headline\n\n")
				.append("| Metric | Result |\n|---|---|\n")
				.append(row("Retrieval hit@" + k + " (hybrid)", count(answerable, r -> r.hybridRank() != null) + "/" + n))
				.append(row("Answered and cited an expected page", count(answerable, r -> r.answered() && r.citedExpected()) + "/" + n))
				.append(row("Answer contains the expected facts", count(answerable, AnswerableResult::containsFacts) + "/" + n))
				.append(row("Unanswerable questions refused", count(unanswerable, UnanswerableResult::refused) + "/" + unanswerable.size()))
				.append("\n");

		md.append("## Retrieval: hybrid vs single search\n\n")
				.append("A hit means an expected (document, page) appears in the top ").append(k)
				.append(" results. MRR is the mean of 1/rank of the first hit (0 when missed).\n\n")
				.append("| Search | hit@1 | hit@").append(k).append(" | MRR@").append(k).append(" |\n|---|---|---|---|\n")
				.append(retrievalRow("Hybrid (vector + keyword, RRF)", AnswerableResult::hybridRank))
				.append(retrievalRow("Vector only (pgvector cosine)", AnswerableResult::vectorRank))
				.append(retrievalRow("Keyword only (Postgres full-text)", AnswerableResult::keywordRank))
				.append("\n");

		List<Double> answerSims = answerable.stream().filter(r -> r.error() == null)
				.map(AnswerableResult::topSimilarity).sorted().toList();
		List<Double> refuseSims = unanswerable.stream().filter(r -> r.error() == null)
				.map(UnanswerableResult::topSimilarity).sorted().toList();
		md.append("## Best-source similarity (input for the refusal threshold)\n\n")
				.append("Highest cosine similarity between the question and any of its top ").append(k)
				.append(" sources.\n\n")
				.append("| Questions | min | median | max |\n|---|---|---|---|\n")
				.append(distributionRow("Answerable", answerSims))
				.append(distributionRow("Unanswerable", refuseSims))
				.append("\n");

		md.append("### Threshold sweep\n\n")
				.append("If questions whose best source is below the threshold were refused before calling the model:\n\n")
				.append("| Threshold | Answerable kept | Unanswerable blocked |\n|---|---|---|\n");
		for (int step = 0; step <= 16; step++) {
			double t = 0.40 + step * 0.025;
			long kept = answerSims.stream().filter(s -> s >= t).count();
			long blocked = refuseSims.stream().filter(s -> s < t).count();
			md.append("| ").append(fmt(t)).append(" | ").append(kept).append("/").append(answerSims.size())
					.append(" | ").append(blocked).append("/").append(refuseSims.size()).append(" |\n");
		}
		md.append("\n");

		md.append("## Answerable questions\n\n")
				.append("| ID | Question | Expected | Hybrid rank | Vector rank | Keyword rank | Best sim. | Answered | Cited expected | Facts |\n")
				.append("|---|---|---|---|---|---|---|---|---|---|\n");
		for (AnswerableResult r : answerable) {
			md.append("| ").append(r.question().id())
					.append(" | ").append(cell(r.question().question()))
					.append(" | ").append(cell(String.join("; ", r.question().expected().stream().map(Object::toString).toList())))
					.append(" | ").append(rankCell(r.hybridRank()))
					.append(" | ").append(rankCell(r.vectorRank()))
					.append(" | ").append(rankCell(r.keywordRank()))
					.append(" | ").append(fmt(r.topSimilarity()))
					.append(" | ").append(tick(r.answered()))
					.append(" | ").append(tick(r.citedExpected()))
					.append(" | ").append(tick(r.containsFacts()))
					.append(" |\n");
		}
		md.append("\n## Unanswerable questions\n\n")
				.append("Refusal layers: `NO_RELEVANT_SOURCES` = similarity threshold, no model call; ")
				.append("`NOT_IN_SOURCES` = the model found no answer in the sources; ")
				.append("`UNGROUNDED_ANSWER` = answer withheld because it cited no real source.\n\n")
				.append("| ID | Question | Best source | Best sim. | Refused | Refused by |\n|---|---|---|---|---|---|\n");
		for (UnanswerableResult r : unanswerable) {
			md.append("| ").append(r.question().id())
					.append(" | ").append(cell(r.question().question()))
					.append(" | ").append(cell(r.topSource()))
					.append(" | ").append(fmt(r.topSimilarity()))
					.append(" | ").append(tick(r.refused()))
					.append(" | ").append(r.refused() ? "`" + r.refusalReason() + "`" : "")
					.append(" |\n");
		}

		md.append("\n## Answers given\n\n");
		for (AnswerableResult r : answerable) {
			md.append("- **").append(r.question().id()).append("** ").append(cell(r.question().question())).append("<br>")
					.append(r.error() != null ? "ERROR: " + cell(r.error()) : cell(r.answer()))
					.append(r.citations().isEmpty() ? "" : " _(cites: " + String.join(", ", r.citations()) + ")_")
					.append("\n");
		}
		for (UnanswerableResult r : unanswerable) {
			md.append("- **").append(r.question().id()).append("** ").append(cell(r.question().question())).append("<br>")
					.append(r.error() != null ? "ERROR: " + cell(r.error()) : cell(r.answer())).append("\n");
		}

		md.append("\n## Settings\n\n```\n").append(String.join("\n", settings)).append("\n```\n\n")
				.append("## Method\n\n")
				.append("1. A fresh Postgres + pgvector container is started and the three sample documents are ingested ")
				.append("(page-bounded chunks, embedded with Gemini).\n")
				.append("2. For each question, the same question embedding is used for three searches: hybrid (the ")
				.append("production path), vector only and keyword only. Each is scored against the expected pages.\n")
				.append("3. The question is then sent through the full `/ask` pipeline. An answer counts when it is ")
				.append("answered, cites at least one expected page, and (separately) contains the expected facts.\n")
				.append("4. Unanswerable questions count when SpecLens refuses.\n")
				.append("5. Model output can vary slightly between runs; retrieval numbers are deterministic for a ")
				.append("given embedding model.\n");
		return md.toString();
	}

	private String retrievalRow(String name, Function<AnswerableResult, Integer> rankOf) {
		int n = answerable.size();
		long hit1 = answerable.stream().map(rankOf).filter(Objects::nonNull).filter(r -> r == 1).count();
		long hitK = answerable.stream().map(rankOf).filter(Objects::nonNull).count();
		double mrr = answerable.stream().map(rankOf).mapToDouble(r -> r == null ? 0 : 1.0 / r).sum() / n;
		return "| " + name + " | " + hit1 + "/" + n + " | " + hitK + "/" + n + " | " + fmt(mrr) + " |\n";
	}

	private static String distributionRow(String name, List<Double> sorted) {
		if (sorted.isEmpty()) {
			return "| " + name + " | - | - | - |\n";
		}
		double median = sorted.size() % 2 == 1 ? sorted.get(sorted.size() / 2)
				: (sorted.get(sorted.size() / 2 - 1) + sorted.get(sorted.size() / 2)) / 2;
		return "| " + name + " | " + fmt(sorted.getFirst()) + " | " + fmt(median) + " | " + fmt(sorted.getLast())
				+ " |\n";
	}

	private static <T> long count(Collection<T> items, Predicate<T> test) {
		return items.stream().filter(test).count();
	}

	private static String row(String metric, String value) {
		return "| " + metric + " | **" + value + "** |\n";
	}

	private static String rankCell(Integer rank) {
		return rank == null ? "miss" : rank.toString();
	}

	private static String tick(boolean value) {
		return value ? "yes" : "**no**";
	}

	private static String fmt(double value) {
		return String.format(Locale.ROOT, "%.3f", value);
	}

	/** Make text safe inside a Markdown table cell. */
	private static String cell(String text) {
		return text == null ? "" : text.replace("|", "\\|").replaceAll("\\s+", " ").strip();
	}

}
